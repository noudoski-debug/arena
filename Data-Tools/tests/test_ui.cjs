const fs=require('fs');
const assert=require('node:assert/strict');
const {JSDOM,VirtualConsole}=require('jsdom');
const errors=[];
const console=new VirtualConsole();console.on('jsdomError',e=>errors.push(e.message));
const html=fs.readFileSync(require('path').join(__dirname,'../examples/demo.html'),'utf8');
const dom=new JSDOM(html,{runScripts:'dangerously',virtualConsole:console,beforeParse(w){
 w.ResizeObserver=class{constructor(cb){this.cb=cb}observe(){this.cb()}disconnect(){}};
 w.Element.prototype.getBoundingClientRect=()=>({x:0,y:0,left:0,top:0,width:1100,height:750,right:1100,bottom:750});
}});
const d=dom.window.document;
assert.equal(d.querySelectorAll('.node').length,12);
assert.equal(d.querySelectorAll('.edge').length,11);
assert.equal(d.querySelector('#nodes-count').textContent,'12');
const input=d.querySelector('#filter');input.value='field-notes';input.dispatchEvent(new dom.window.Event('input'));
assert.equal([...d.querySelectorAll('.node')].filter(n=>n.style.display!=='none').length,1);
input.value='';input.dispatchEvent(new dom.window.Event('input'));
[...d.querySelectorAll('.node')].find(n=>n.getAttribute('aria-label')==='field-notes').dispatchEvent(new dom.window.Event('click'));
assert(d.querySelector('#details').classList.contains('visible'));
assert.equal(d.querySelector('#detail-title').textContent,'field-notes');
assert.equal(d.querySelector('#detail-link').getAttribute('rel'),'noopener noreferrer');
d.querySelector('#back').click();assert.equal(d.querySelector('#overview').style.display,'');
[...d.querySelectorAll('#filters button')].find(b=>b.textContent==='Не проверено').click();
assert.equal([...d.querySelectorAll('.node')].filter(n=>n.style.display!=='none').length,2);
d.querySelector('#zoom-in').click();d.querySelector('#zoom-out').click();d.querySelector('#fit').click();
d.querySelector('#labels').click();assert([...d.querySelectorAll('.node text')].every(n=>n.style.display==='none'));
assert.deepEqual(errors,[]);
process.stdout.write('PASS: offline DOM render, 12 nodes, filters, details, links, zoom and labels\n');
dom.window.close();
